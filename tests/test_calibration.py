"""Camera calibration from the monitor ChArUco pattern, a lens with distortion, and the
frame window scale. The distorted views are generated by remapping ideal renders through
the known lens, independently of the code under test."""
import cv2
import numpy as np
import pytest

from foto_olcum import calib, features2d
from foto_olcum import frame as fr
from foto_olcum import synth
from foto_olcum.project import Measurement, Project
from synthetic_run import DEFAULT_PART

W, H = 3000, 2250
K = np.array([[2600.0, 0, 1510.0], [0, 2600.0, 1118.0], [0, 0, 1]])
DIST = np.array([-0.08, 0.05, 0.0004, -0.0003, 0.0])


def _distort_maps():
    """For every pixel of the distorted image, where it comes from in the ideal image."""
    xs, ys = np.meshgrid(np.arange(W, dtype=np.float32), np.arange(H, dtype=np.float32))
    pts = np.stack([xs.ravel(), ys.ravel()], 1).reshape(-1, 1, 2)
    ideal = cv2.undistortPoints(pts, K, DIST, P=K).reshape(H, W, 2)
    return ideal[..., 0].astype(np.float32), ideal[..., 1].astype(np.float32)


@pytest.fixture(scope="module")
def maps():
    return _distort_maps()


def _view(board_img, rvec, tvec, mx, my, rng):
    """Board PNG on the z=0 plane (1 px = 0.25 mm) seen by the camera, then distorted."""
    s = 0.25
    R = cv2.Rodrigues(np.asarray(rvec, float))[0]
    Hm = K @ np.c_[R[:, 0] * s, R[:, 1] * s, np.asarray(tvec, float)]
    ideal = cv2.warpPerspective(board_img, Hm, (W, H), flags=cv2.INTER_AREA, borderValue=60)
    img = cv2.remap(ideal, mx, my, cv2.INTER_LINEAR, borderValue=60)
    img = np.clip(img + rng.normal(0, 2, img.shape), 0, 255).astype(np.uint8)
    return cv2.GaussianBlur(img, (0, 0), 0.7)


def test_calibrate_recovers_lens(tmp_path, monkeypatch, maps):
    monkeypatch.setenv("FOTO_OLCUM_PROJECTS", str(tmp_path))
    png = calib.make_pattern(tmp_path / "pattern.png", 1920, 1080)
    board = cv2.imread(str(png), 0)
    rng = np.random.default_rng(0)
    paths = []
    bw, bh = board.shape[1] * 0.25, board.shape[0] * 0.25
    # as instructed to the user: varied angles, and the pattern sometimes reaching the corners
    spots = [(0, 0)] * 4 + [(sx, sy) for sx in (-1, 1) for sy in (-1, 1)] * 2
    for i, (sx, sy) in enumerate(spots):
        # board rows run down like image rows, so a near-identity rotation views it unmirrored
        rvec = np.array([rng.uniform(-0.45, 0.45), rng.uniform(-0.45, 0.45), rng.uniform(-0.3, 0.3)])
        R = cv2.Rodrigues(rvec)[0]
        center = np.array([bw / 2, bh / 2, 0])
        z = rng.uniform(620, 800)
        off = np.array([sx * 0.2 * z + rng.uniform(-20, 20), sy * 0.16 * z + rng.uniform(-15, 15), z])
        tvec = off - R @ center
        img = _view(board, rvec, tvec, *maps, rng)
        paths.append(tmp_path / f"cal_{i:02d}.png")
        cv2.imwrite(str(paths[-1]), img)
    r = calib.calibrate(paths, "testphone")
    assert r["n_used"] >= 10 and r["rms_px"] < 0.5, r
    cam = calib.Camera.load("testphone")
    Kc, dc = np.array(cam.K), np.array(cam.dist)
    assert abs(Kc[0, 0] / K[0, 0] - 1) < 0.01 and abs(Kc[1, 1] / K[1, 1] - 1) < 0.01, Kc
    # what matters is measuring with the *estimated* model: see the pipeline test below
    _measure_distorted(tmp_path, maps, "testphone")


def test_pipeline_with_lens_distortion(tmp_path, monkeypatch, maps):
    """Distorted photo measured with the exact lens model."""
    monkeypatch.setenv("FOTO_OLCUM_PROJECTS", str(tmp_path))
    calib.Camera("lens", [W, H], K.tolist(), DIST.tolist(), 0.0, 0, "charuco", 0.003).save()
    _measure_distorted(tmp_path, maps, "lens")


def _measure_distorted(tmp_path, maps, camera):
    f = fr.layout("synth")
    fr.build(f, tmp_path / "_cerceveler" / "synth")
    cam = synth.Cam(f=K[0, 0], w=W, h=H)
    cam.K = lambda: K
    part = synth.Part(**DEFAULT_PART)
    ideal = np.asarray(synth.render(part, f, cam, seed=4).convert("L"))
    photo = tmp_path / "dist.png"
    cv2.imwrite(str(photo), cv2.remap(ideal, *maps, cv2.INTER_LINEAR))
    p = Project.create(f"lens_{camera}")
    pid = p.add_photo(photo, "silhouette")
    p.update_photo(pid, frame="synth", camera=camera)
    features2d.process_photo(p, pid)
    p.put_measurement(Measurement("thickness", part.thickness, 0.03, "caliper", locked=True))
    res = features2d.extract(p, pid)
    assert len(res["outer"]["vertices"]) == 5 and len(res["holes"]) == 3
    dias = sorted(h["dia"] for h in res["holes"])
    assert np.allclose(dias, sorted(d for *_, d in part.holes), atol=0.1), dias
    v2 = res["outer"]["vertices"][1]
    assert abs(v2["x"] - 80.0) < 0.15, v2


def test_measured_window_scales_markers():
    f = fr.layout("s")
    x0, y0, x1, y1 = f.window
    before = f.marker_corners(0)
    f.measured_window = [(x1 - x0) * 1.005, (y1 - y0) * 1.005]
    after = f.marker_corners(0)
    c = np.array([(x0 + x1) / 2, (y0 + y1) / 2])
    assert np.allclose(after[:, :2] - c, (before[:, :2] - c) * 1.005)
    assert f.scale_sigma_rel < 0.001
